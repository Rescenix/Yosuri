import fs from 'node:fs/promises'
import PptxGenJS from 'pptxgenjs'

const [, , inputPath, outputPath] = process.argv
if (!inputPath || !outputPath) throw new Error('usage: render-agent-pptx.mjs input.json output.pptx')
const source = JSON.parse(await fs.readFile(inputPath, 'utf8'))
const pptx = new PptxGenJS()
pptx.layout = 'LAYOUT_WIDE'
pptx.author = 'Rescene Agent OS'
pptx.subject = source.topic || ''
pptx.title = source.topic || 'Agent delivery'
pptx.company = 'Rescene'
pptx.lang = 'zh-CN'
pptx.theme = {
  headFontFace: 'Microsoft YaHei', bodyFontFace: 'Microsoft YaHei', lang: 'zh-CN',
}

const cover = pptx.addSlide()
cover.background = { color: '08111F' }
cover.addShape(pptx.ShapeType.rect, { x: 0, y: 0, w: 13.333, h: 0.12, line: { color: '34D399' }, fill: { color: '34D399' } })
cover.addText(source.topic || 'Agent 交付', { x: 0.85, y: 2.2, w: 11.6, h: 1.35, fontSize: 34, bold: true, color: 'F8FAFC', margin: 0, breakLine: false })
cover.addText('REAL OUTPUT · GENERATED BY RESCENE AGENTS', { x: 0.88, y: 4.15, w: 7, h: 0.35, fontSize: 10, bold: true, color: '34D399', charSpacing: 1.8, margin: 0 })

for (const [index, page] of (source.slides || []).entries()) {
  const slide = pptx.addSlide()
  slide.background = { color: index % 2 ? 'F8FAFC' : 'FFFFFF' }
  slide.addText(String(index + 1).padStart(2, '0'), { x: 0.72, y: 0.55, w: 0.62, h: 0.35, fontSize: 11, bold: true, color: '10B981', margin: 0 })
  slide.addText(page.title || `第 ${index + 1} 页`, { x: 1.45, y: 0.48, w: 10.8, h: 0.65, fontSize: 25, bold: true, color: '0F172A', margin: 0 })
  slide.addShape(pptx.ShapeType.line, { x: 0.72, y: 1.34, w: 11.86, h: 0, line: { color: 'DDE5E1', width: 1 } })
  const rows = (page.points || []).slice(0, 5)
  rows.forEach((point, row) => {
    const y = 1.75 + row * 0.92
    slide.addShape(pptx.ShapeType.ellipse, { x: 0.9, y: y + 0.12, w: 0.19, h: 0.19, line: { color: '34D399' }, fill: { color: '34D399' } })
    slide.addText(point, { x: 1.34, y, w: 10.7, h: 0.55, fontSize: 19, color: '26332D', margin: 0, breakLine: false, fit: 'shrink' })
  })
  slide.addText('RESCENE COMPANY OS', { x: 10.25, y: 7.03, w: 2.25, h: 0.2, align: 'right', fontSize: 7.5, bold: true, color: '94A3B8', margin: 0 })
}

await pptx.writeFile({ fileName: outputPath })
